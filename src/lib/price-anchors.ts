export function trendPrice(anchors: PriceAnchor[], date: Date): number {
  const t = Date.UTC(date.getUTCFullYear(), date.getUTCMonth(), date.getUTCDate());
  const points = anchors.map((anchor) => {
    const [year, month, day] = anchor.date.split("-").map(Number);
    return { t: Date.UTC(year, month - 1, day), price: anchor.price };
  });
  if (t <= points[0].t) return points[0].price;
  const last = points[points.length - 1];
  if (t >= last.t) return last.price;
  let index = 1;
  while (points[index].t < t) index += 1;
  const left = points[index - 1];
  const right = points[index];
  const weight = (t - left.t) / (right.t - left.t);
  return Math.exp(Math.log(left.price) * (1 - weight) + Math.log(right.price) * weight);
}

